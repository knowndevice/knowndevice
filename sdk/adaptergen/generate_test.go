func testOptions(t testing.TB) Options {
	t.Helper()
	root, err := filepath.EvalSymlinks(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	sdk, err := filepath.Abs("../..")
	if err == nil {
		sdk, err = filepath.EvalSymlinks(sdk)
	}
	if err != nil {
		t.Fatal(err)
	}
	return Options{Root: root, Directory: "sample", Name: "sample", Module: "adapter-test.local/sample", SDKReplace: sdk}
}

func TestGenerationIsDeterministicAndExclusive(t *testing.T) {
	options := testOptions(t)
	first, err := Generate(options)
	if err != nil {
		t.Fatal(err)
	}
	if len(first.Files) != 13 {
		t.Fatalf("unexpected generated file count: %d", len(first.Files))
	}
	options.Directory = "second"
	second, err := Generate(options)
	if err != nil || !reflect.DeepEqual(first.Files, second.Files) {
		t.Fatal("file metadata differs for identical content options", err)
	}
	for _, file := range first.Files {
		left, err := os.ReadFile(filepath.Join(options.Root, first.Directory, file.Path))
		if err != nil {
			t.Fatal(err)
		}
		right, err := os.ReadFile(filepath.Join(options.Root, second.Directory, file.Path))
		if err != nil || !bytes.Equal(left, right) {
			t.Fatal("generated bytes differ", err)
		}
		info, err := os.Stat(filepath.Join(options.Root, first.Directory, file.Path))
		if err != nil || info.Mode().String() != file.Mode {
			t.Fatal("generated mode mismatch", err)
		}
	}
	before, err := os.ReadFile(filepath.Join(options.Root, "second", "adapter.go"))
	if err != nil {
		t.Fatal(err)
	}
	if _, err := Generate(options); !errors.Is(err, ErrDestination) {
		t.Fatal("existing destination accepted", err)
	}
	after, err := os.ReadFile(filepath.Join(options.Root, "second", "adapter.go"))
	if err != nil || !bytes.Equal(before, after) {
		t.Fatal("existing adapter changed", err)
	}
}

func TestGenerationRejectsNamesModulesAndTraversalBeforeWriting(t *testing.T) {
	mutations := []func(*Options){
		func(o *Options) { o.Name = "../../escape" },
		func(o *Options) { o.Name = "-sample" },
		func(o *Options) { o.Name = "con" },
		func(o *Options) { o.Name = "sample\nreplace" },
		func(o *Options) { o.Name = strings.Repeat("a", 64) },
		func(o *Options) { o.Directory = "." },
		func(o *Options) { o.Directory = ".." },
		func(o *Options) { o.Directory = "nested/sample" },
		func(o *Options) { o.Directory = "/sample" },
		func(o *Options) { o.Directory = "nested\\sample" },
		func(o *Options) { o.Module = "no-domain/sample" },
		func(o *Options) { o.Module = "example.com/../sample" },
		func(o *Options) { o.Module = "example.com//sample" },
		func(o *Options) { o.Module = "example.com/sample\nreplace x => /etc" },
		func(o *Options) { o.Module = "example.com/sample`command`" },
		func(o *Options) { o.Module = "example.com/$(command)" },
		func(o *Options) { o.Module = "example.com/a.git" },
		func(o *Options) { o.Module = "example.com/con" },
		func(o *Options) { o.Module = "example.com/nul.txt" },
		func(o *Options) { o.Module = "example.com/a/v1" },
		func(o *Options) { o.Module = "example.com/a/v02" },
		func(o *Options) { o.Module = "gopkg.in/a" },
		func(o *Options) { o.Module = "knowndevice.local/knowndevice" },
		func(o *Options) { o.Root = "relative" },
		func(o *Options) { o.Root += "/." },
		func(o *Options) { o.SDKReplace += "/../knowndevice" },
	}
	for i, mutate := range mutations {
		t.Run(string(rune('a'+i)), func(t *testing.T) {
			options := testOptions(t)
			originalRoot := options.Root
			mutate(&options)
			if _, err := Generate(options); !errors.Is(err, ErrOptions) {
				t.Fatal("invalid options accepted", err)
			}
			entries, err := os.ReadDir(originalRoot)
			if err != nil || len(entries) != 0 {
				t.Fatal("invalid options wrote output", err)
			}
		})
	}
}

func TestSDKReplaceIsQuotedData(t *testing.T) {
	options := testOptions(t)
	selected := filepath.Join(options.Root, "sdk space \" $(ignored) `ignored`")
	if os.Mkdir(selected, 0700) != nil || os.WriteFile(filepath.Join(selected, "go.mod"), []byte("module knowndevice.local/knowndevice\n"), 0600) != nil {
		t.Fatal("test SDK module creation failed")
	}
	options.SDKReplace = selected
	if _, err := Generate(options); err != nil {
		t.Fatal(err)
	}
	command := exec.Command("go", "mod", "edit", "-json")
	command.Dir = filepath.Join(options.Root, options.Directory)
	output, err := command.Output()
	if err != nil {
		t.Fatal("quoted module replacement was not accepted", err)
	}
	var parsed struct {
		Replace []struct{ New struct{ Path string } }
	}
	if json.Unmarshal(output, &parsed) != nil || len(parsed.Replace) != 1 || parsed.Replace[0].New.Path != selected {
		t.Fatal("replacement changed while parsing go.mod")
	}
}

func TestGenerationPreservesExistingDestinationAndRefusesSymlinks(t *testing.T) {
	for _, kind := range []string{"file", "directory", "symlink", "root-symlink", "root-component-symlink", "sdk-symlink", "sdk-module-symlink"} {
		t.Run(kind, func(t *testing.T) {
			options := testOptions(t)
			outside, err := filepath.EvalSymlinks(t.TempDir())
			if err != nil {
				t.Fatal(err)
			}
			sentinel := filepath.Join(outside, "preserve")
			if os.WriteFile(sentinel, []byte("user work"), 0600) != nil {
				t.Fatal("sentinel creation failed")
			}
			switch kind {
			case "file":
				err = os.WriteFile(filepath.Join(options.Root, options.Directory), []byte("user work"), 0600)
			case "directory":
				err = os.Mkdir(filepath.Join(options.Root, options.Directory), 0700)
			case "symlink":
				err = os.Symlink(outside, filepath.Join(options.Root, options.Directory))
			case "root-symlink":
				err = os.Symlink(outside, filepath.Join(options.Root, "link"))
				options.Root = filepath.Join(options.Root, "link")
			case "root-component-symlink":
				err = os.Mkdir(filepath.Join(outside, "inner"), 0700)
				if err == nil {
					err = os.Symlink(outside, filepath.Join(options.Root, "link"))
				}
				options.Root = filepath.Join(options.Root, "link", "inner")
			case "sdk-symlink":
				err = os.Symlink(options.SDKReplace, filepath.Join(options.Root, "sdk"))
				options.SDKReplace = filepath.Join(options.Root, "sdk")
			case "sdk-module-symlink":
				err = os.Symlink(filepath.Join(options.SDKReplace, "go.mod"), filepath.Join(outside, "go.mod"))
				options.SDKReplace = outside
			}
			if err != nil {
				t.Fatal(err)
			}
			if _, err := Generate(options); err == nil {
				t.Fatal("existing destination or symlink accepted")
			}
			data, err := os.ReadFile(sentinel)
			if err != nil || string(data) != "user work" {
				t.Fatal("outside user work changed", err)
			}
			if _, err := os.Stat(filepath.Join(outside, "adapter.go")); !os.IsNotExist(err) {
				t.Fatal("generation escaped selected destination")
			}
		})
	}
}

func TestConcurrentGenerationHasOneOwner(t *testing.T) {
	options := testOptions(t)
	var group sync.WaitGroup
	errorsSeen := make(chan error, 8)
	for range 8 {
		group.Add(1)
		go func() { defer group.Done(); _, err := Generate(options); errorsSeen <- err }()
	}
	group.Wait()
	close(errorsSeen)
	successes := 0
	for err := range errorsSeen {
		if err == nil {
			successes++
		} else if !errors.Is(err, ErrDestination) {
			t.Fatal("unexpected concurrent generation error", err)
		}
	}
	if successes != 1 {
		t.Fatalf("expected one exclusive generation, got %d", successes)
	}
}

func TestRacedDestinationSymlinkCannotOverwriteOutsideFile(t *testing.T) {
	options := testOptions(t)
	outside, err := filepath.EvalSymlinks(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	sentinel := filepath.Join(outside, "preserve")
	if os.WriteFile(sentinel, []byte("user work"), 0600) != nil {
		t.Fatal("sentinel creation failed")
	}
	for attempt := range 24 {
		options.Directory = "race-" + string(rune('a'+attempt))
		stop := make(chan struct{})
		done := make(chan struct{})
		go func(directory string) {
			defer close(done)
			for {
				select {
				case <-stop:
					return
				default:
				}
				if os.Symlink(sentinel, filepath.Join(options.Root, directory, "adapter.go")) == nil {
					return
				}
			}
		}(options.Directory)
		_, err := Generate(options)
		close(stop)
		<-done
		if err != nil && !errors.Is(err, ErrGeneration) {
			t.Fatal("unexpected raced generation result", err)
		}
		data, err := os.ReadFile(sentinel)
		if err != nil || string(data) != "user work" {
			t.Fatal("raced symlink overwrote user work", err)
		}
	}
}

func TestTemplateMatchesStrictSchemaAndPublicImports(t *testing.T) {
	options := testOptions(t)
	files, err := render(options)
	if err != nil {
		t.Fatal(err)
	}
	var schema jsonschema.Schema
	if json.Unmarshal(ManifestSchema, &schema) != nil {
		t.Fatal("manifest schema invalid")
	}
	resolved, err := schema.Resolve(nil)
	if err != nil {
		t.Fatal(err)
	}
	for _, file := range files {
		if file.path == "adapter-template.json" {
			var value map[string]any
			if json.Unmarshal(file.data, &value) != nil || resolved.Validate(value) != nil {
				t.Fatal("template does not match its schema")
			}
			value["unknownField"] = true
			if resolved.Validate(value) == nil {
				t.Fatal("schema accepted an unknown field")
			}
		}
		if strings.HasSuffix(file.path, ".go") {
			parsed, err := parser.ParseFile(token.NewFileSet(), file.path, file.data, parser.ImportsOnly)
			if err != nil {
				t.Fatal(err)
			}
			ast.Inspect(parsed, func(node ast.Node) bool {
				if imported, ok := node.(*ast.ImportSpec); ok && (strings.Contains(imported.Path.Value, "/internal/") || strings.Contains(imported.Path.Value, "/.work/")) {
					t.Error("generated source imports a private implementation")
				}
				return true
			})
		}
	}
	if _, err := Bind(options.Name, nil, strings.Repeat("a", 64)); !errors.Is(err, ErrManifest) {
		t.Fatal("manifest accepted an absent snapshot")
	}
}

func TestGeneratedExternalModuleBuilds(t *testing.T) {
	options := testOptions(t)
	if _, err := Generate(options); err != nil {
		t.Fatal(err)
	}
	ctx, cancel := context.WithTimeout(context.Background(), time.Minute)
	defer cancel()
	command := exec.CommandContext(ctx, "go", "build", "./...")
	command.Dir = filepath.Join(options.Root, options.Directory)
	output, err := command.CombinedOutput()
	if err != nil {
		t.Fatalf("external public-only generated module did not build: %v\n%s", err, output)
	}
}

func FuzzGenerationInputValidation(f *testing.F) {
	for _, seed := range [][3]string{{"sample", "sample", "example.local/sample"}, {"../escape", "sample", "example.local/sample"}, {"sample", "a/b", "example.local/sample"}, {"sample", "sample", "example.local/a\nreplace x => /tmp"}} {
		f.Add(seed[0], seed[1], seed[2])
	}
	f.Fuzz(func(t *testing.T, name, directory, module string) {
		if len(name)+len(directory)+len(module) > 1024 {
			return
		}
		if validName(name) && (strings.ContainsAny(name, "/\\\n\r\x00") || name == "." || name == "..") {
			t.Fatal("unsafe name accepted")
		}
		if validName(directory) && !filepath.IsLocal(directory) {
			t.Fatal("nonlocal directory accepted")
		}
		if validModule(module) && strings.ContainsAny(module, "\r\n\x00\"`$\\") {
			t.Fatal("module injection accepted")
		}
		if validName(name) && validName(directory) && validModule(module) {
			files, err := render(Options{Name: name, Directory: directory, Module: module, SDKReplace: "/explicit/local-sdk"})
			if err != nil || len(files) == 0 {
				t.Fatal("valid bounded inputs did not render", err)
			}
			for _, file := range files {
				if !filepath.IsLocal(file.path) {
					t.Fatal("generated path escaped")
				}
			}
		}
	})
}
